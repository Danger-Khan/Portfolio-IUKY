/**
 * engine.js — Slicer Lab, running entirely in the browser.
 *
 * Three real, working tools, no server or upload involved:
 *   1. G-code Analyzer — reads a .gcode file the user picks via the file
 *      input (File API, works offline and over file://) and pulls out the
 *      slicer's own summary comments (print time, filament used, cost,
 *      material, temperatures) plus a few computed stats (layer count from
 *      ;LAYER_CHANGE markers, line count).
 *   2. Material Settings Advisor — a fixed reference table of real FDM
 *      print-setting ranges per material (same data as database.sql).
 *   3. Filament Cost Calculator — weight + price/kg -> cost, or budget +
 *      price/kg -> max weight.
 *
 * material_profiles / real_jobs here are a direct JS copy of database.sql
 * (a browser can't read a .sql file without a server); analyzer.py is the
 * same regex-based parsing again, in Python, for the offline/CLI companion.
 */
(function () {
  'use strict';

  var MATERIAL_PROFILES = [
    { material: 'PLA', nozzleMin: 190, nozzleMax: 220, bedMin: 50, bedMax: 60,
      fan: '100% after the first layer', speed: '40-60 mm/s',
      notes: 'Easiest material to print — low warping, no enclosure needed. Lowest heat resistance of the common filaments, so not great for hot environments (e.g. a car dashboard).' },
    { material: 'PETG', nozzleMin: 230, nozzleMax: 250, bedMin: 70, bedMax: 90,
      fan: '30-50% — too much fan causes weak layer bonding', speed: '40-60 mm/s',
      notes: "Stronger and more temperature-resistant than PLA, but strings more. Every real print in this portfolio's CAM folder was PETG (see Real Jobs below) at 230-240°C / 80°C bed." },
    { material: 'ABS', nozzleMin: 230, nozzleMax: 250, bedMin: 90, bedMax: 110,
      fan: '0-10% — high fan causes layer cracking/warping', speed: '40-60 mm/s',
      notes: 'Warps badly without an enclosure and a heated bed; needs ventilation (fumes). More impact- and heat-resistant than PLA/PETG.' },
    { material: 'TPU/FLEX', nozzleMin: 210, nozzleMax: 230, bedMin: 30, bedMax: 60,
      fan: '20-50%', speed: '15-30 mm/s (slow — direct drive helps a lot)',
      notes: "Flexible filament — slow print speeds and minimal retraction avoid jams in a bowden setup. The 11h43m FLEX print in this portfolio's CAM folder ran at 190°C nozzle / 40°C bed." },
    { material: 'ASA', nozzleMin: 240, nozzleMax: 260, bedMin: 90, bedMax: 110,
      fan: '0-10%', speed: '40-60 mm/s',
      notes: 'ABS-like properties with better UV resistance — a common choice for outdoor parts. Needs an enclosure like ABS.' },
    { material: 'Nylon', nozzleMin: 240, nozzleMax: 270, bedMin: 70, bedMax: 90,
      fan: '0-20%', speed: '30-50 mm/s',
      notes: 'Very tough and abrasion-resistant, but hygroscopic — absorbs moisture from the air and must be dried before printing or it will bubble/pop mid-print.' }
  ];

  // Cost is whatever currency the original PrusaSlicer material-cost profile
  // was configured in — not verified, so shown as a bare number.
  var REAL_JOBS = [
    { filename: '33m,PETG,cabletiebelttensioner.gcode', part: 'Cable Tie Belt Tensioner', material: 'PETG', time: '33m 18s', g: 4.09, cost: 163.57, nozzle: 240, bed: 80, note: '' },
    { filename: '18m,PETG,riemenspanner.gcode', part: 'Riemenspanner', material: 'PETG', time: '17m 43s', g: 2.24, cost: 89.60, nozzle: 240, bed: 80, note: '' },
    { filename: '1h49m,PETG,box.gcode', part: 'Box', material: 'PETG', time: '1h 49m 18s', g: 56.50, cost: 2260.13, nozzle: 230, bed: 80, note: '' },
    { filename: '40m,PETG,box.gcode', part: 'Box (resumed print)', material: 'PETG', time: '1h 49m 18s', g: 56.50, cost: 2260.13, nozzle: 230, bed: 80,
      note: "Filename says 40m, but the file's own embedded stats report the same totals as the 1h49m box above — its G-code body starts mid-object at Z38.3mm, consistent with a resliced resume-after-pause file. Shown exactly as the file reports it, not corrected." },
    { filename: '11h43m,FLEX,pl.gcode', part: 'PL (Recycler part)', material: 'FLEX', time: '11h 43m 27s', g: 70.24, cost: 2458.38, nozzle: 190, bed: 40, note: '' }
  ];

  function escapeHtml(str) {
    return String(str || '').replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }

  // --- G-code parsing ----------------------------------------------------
  function findField(text, pattern) {
    var m = text.match(pattern);
    return m ? m[1].trim() : null;
  }

  function countMatches(text, pattern) {
    var m = text.match(pattern);
    return m ? m.length : 0;
  }

  function parseGcode(text) {
    var generatedBy = findField(text, /;\s*generated by\s+(.+)$/im);
    var printTime = findField(text, /;\s*estimated printing time \(normal mode\)\s*=\s*(.+)$/im);
    var filamentMm = findField(text, /;\s*filament used \[mm\]\s*=\s*([\d.]+)/i);
    var filamentCm3 = findField(text, /;\s*filament used \[cm3\]\s*=\s*([\d.]+)/i);
    var filamentG = findField(text, /;\s*filament used \[g\]\s*=\s*([\d.]+)/i);
    var filamentCost = findField(text, /;\s*filament cost\s*=\s*([\d.]+)/i);
    var material = findField(text, /;\s*filament_type\s*=\s*(\S+)/i);
    var nozzleTemp = findField(text, /;\s*temperature\s*=\s*(\d+)/i);
    var bedTemp = findField(text, /;\s*bed_temperature\s*=\s*(\d+)/i);
    var nozzleDiameter = findField(text, /;\s*nozzle_diameter\s*=\s*([\d.]+)/i);
    var layerHeight = findField(text, /;\s*layer_height\s*=\s*([\d.]+)/i);

    var layerChanges = countMatches(text, /;LAYER_CHANGE/g);
    var lineCount = countMatches(text, /\n/g) + 1;
    var g1Moves = countMatches(text, /^G1 /gm);

    var found = generatedBy || printTime || filamentG || material;

    return {
      found: !!found,
      generatedBy: generatedBy,
      printTime: printTime,
      filamentMm: filamentMm,
      filamentCm3: filamentCm3,
      filamentG: filamentG,
      filamentCost: filamentCost,
      material: material,
      nozzleTemp: nozzleTemp,
      bedTemp: bedTemp,
      nozzleDiameter: nozzleDiameter,
      layerHeight: layerHeight,
      layerChanges: layerChanges,
      lineCount: lineCount,
      g1Moves: g1Moves
    };
  }

  window.SlicerLab = {
    parseGcode: parseGcode,
    materialProfiles: MATERIAL_PROFILES,
    realJobs: REAL_JOBS
  };

  // --- Page wiring ---------------------------------------------------
  document.addEventListener('DOMContentLoaded', function () {
    wireAnalyzer();
    wireMaterialAdvisor();
    wireCostCalculator();
    renderRealJobs();
  });

  function wireAnalyzer() {
    var fileInput = document.getElementById('gcodeFile');
    var resultBox = document.getElementById('analyzerResult');
    var dropNote = document.getElementById('analyzerFileName');
    if (!fileInput || !resultBox) return;

    fileInput.addEventListener('change', function () {
      var file = fileInput.files && fileInput.files[0];
      if (!file) return;
      if (dropNote) dropNote.textContent = file.name + ' (' + (file.size / 1024).toFixed(1) + ' KB)';
      resultBox.innerHTML = '<p class="empty-hint">Reading file…</p>';

      var reader = new FileReader();
      reader.onload = function () {
        var stats = parseGcode(String(reader.result));
        renderAnalyzerResult(stats, resultBox);
      };
      reader.onerror = function () {
        resultBox.innerHTML = '<p class="empty-hint">Could not read that file.</p>';
      };
      reader.readAsText(file);
    });
  }

  function statRow(label, value) {
    if (value === null || value === undefined || value === '') return '';
    return '<tr><th>' + escapeHtml(label) + '</th><td>' + escapeHtml(value) + '</td></tr>';
  }

  function renderAnalyzerResult(s, resultBox) {
    if (!s.found) {
      resultBox.innerHTML =
        '<p class="empty-hint">No PrusaSlicer-style summary comments found in this file — ' +
        'it may use a different slicer\'s comment format, or not be a sliced G-code file at all. ' +
        'Computed stats below are still real, read straight from the file:</p>' +
        '<table class="stat-table">' +
        statRow('Line count', s.lineCount.toLocaleString()) +
        statRow('G1 move commands', s.g1Moves.toLocaleString()) +
        statRow('Layer changes (;LAYER_CHANGE)', s.layerChanges.toLocaleString()) +
        '</table>';
      return;
    }
    resultBox.innerHTML =
      '<table class="stat-table">' +
      statRow('Sliced by', s.generatedBy) +
      statRow('Material', s.material) +
      statRow('Estimated print time', s.printTime) +
      statRow('Filament used', s.filamentG ? s.filamentG + ' g' : null) +
      statRow('Filament length', s.filamentMm ? s.filamentMm + ' mm' : null) +
      statRow('Filament volume', s.filamentCm3 ? s.filamentCm3 + ' cm³' : null) +
      statRow('Filament cost', s.filamentCost ? s.filamentCost + ' (slicer-configured units)' : null) +
      statRow('Nozzle temperature', s.nozzleTemp ? s.nozzleTemp + '°C' : null) +
      statRow('Bed temperature', s.bedTemp ? s.bedTemp + '°C' : null) +
      statRow('Nozzle diameter', s.nozzleDiameter ? s.nozzleDiameter + ' mm' : null) +
      statRow('Layer height', s.layerHeight ? s.layerHeight + ' mm' : null) +
      statRow('Layer changes', s.layerChanges ? s.layerChanges.toLocaleString() : null) +
      statRow('Line count', s.lineCount.toLocaleString()) +
      statRow('G1 move commands', s.g1Moves.toLocaleString()) +
      '</table>';
  }

  function renderRealJobs() {
    var body = document.getElementById('realJobsBody');
    if (!body) return;
    body.innerHTML = REAL_JOBS.map(function (j) {
      var noteHtml = j.note ? '<div class="job-note">' + escapeHtml(j.note) + '</div>' : '';
      return '<tr>' +
        '<td>' + escapeHtml(j.part) + noteHtml + '</td>' +
        '<td>' + escapeHtml(j.material) + '</td>' +
        '<td>' + escapeHtml(j.time) + '</td>' +
        '<td>' + j.g.toFixed(2) + ' g</td>' +
        '<td>' + j.nozzle + '°C / ' + j.bed + '°C</td>' +
        '<td><a href="../Freelance/' + encodeURIComponent(j.filename) + '" download>Download</a></td>' +
        '</tr>';
    }).join('');
  }

  function wireMaterialAdvisor() {
    var select = document.getElementById('materialSelect');
    var box = document.getElementById('materialResult');
    if (!select || !box) return;

    function render() {
      var m = MATERIAL_PROFILES[select.selectedIndex];
      if (!m) return;
      box.innerHTML =
        '<table class="stat-table">' +
        statRow('Nozzle temperature', m.nozzleMin + '-' + m.nozzleMax + '°C') +
        statRow('Bed temperature', m.bedMin + '-' + m.bedMax + '°C') +
        statRow('Cooling fan', m.fan) +
        statRow('Print speed', m.speed) +
        '</table>' +
        '<p class="advisor-notes">' + escapeHtml(m.notes) + '</p>';
    }

    MATERIAL_PROFILES.forEach(function (m, i) {
      var opt = document.createElement('option');
      opt.value = String(i);
      opt.textContent = m.material;
      select.appendChild(opt);
    });
    select.addEventListener('change', render);
    render();
  }

  function wireCostCalculator() {
    var weightInput = document.getElementById('costWeight');
    var priceInput = document.getElementById('costPrice');
    var qtyInput = document.getElementById('costQty');
    var out = document.getElementById('costResult');
    if (!weightInput || !priceInput || !out) return;

    function render() {
      var weightG = parseFloat(weightInput.value);
      var pricePerKg = parseFloat(priceInput.value);
      var qty = parseFloat(qtyInput.value) || 1;
      if (!(weightG > 0) || !(pricePerKg > 0)) {
        out.textContent = 'Enter a weight and a price per kg.';
        return;
      }
      var costPerPart = (weightG / 1000) * pricePerKg;
      var total = costPerPart * qty;
      out.innerHTML =
        '<strong>' + costPerPart.toFixed(2) + '</strong> per part' +
        (qty !== 1 ? ' &nbsp;·&nbsp; <strong>' + total.toFixed(2) + '</strong> for ' + qty + ' parts' : '') +
        ' &nbsp;<span class="hint">(same currency units as the price you entered)</span>';
    }

    [weightInput, priceInput, qtyInput].forEach(function (el) {
      el.addEventListener('input', render);
    });
    render();
  }
})();
